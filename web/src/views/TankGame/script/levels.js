// 初始化碎石墙耐久
function initCrackHp(map) {
  const crackHp = {};
  for (let r = 0; r < ROWS; r++) {
    for (let c = 0; c < COLS; c++) {
      if (map[r] && map[r][c] === CRACK) {
        crackHp[protectedKey(c, r)] = 2 + Math.floor(Math.random() * 2);
      }
    }
  }
  return crackHp;
}

